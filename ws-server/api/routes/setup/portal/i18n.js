/**
 * Builds the client runtime script incorporating dictionaries, lookup helper,
 * and DOM translation runner.
 */
function buildClientScript() {
    return `/**
 * TaNoClo Setup Portal i18n Runtime
 */
(function() {
    const LOCALES = ${JSON.stringify(DICTIONARIES)};
    const SUPPORTED = ${JSON.stringify(SUPPORTED_LOCALES)};
    const DEFAULT_LOCALE = '${DEFAULT_LOCALE}';

    function getCookie(name) {
        const matches = document.cookie.match(new RegExp('(?:^|; )' + name.replace(/([\\.$?*|{}\\(\\)\\[\\]\\\\\\/\\+^])/g, '\\\\$1') + '=([^;]*)'));
        return matches ? decodeURIComponent(matches[1]) : undefined;
    }

    function setCookie(name, val, days = 365) {
        const date = new Date();
        date.setTime(date.getTime() + (days * 24 * 60 * 60 * 1000));
        document.cookie = name + '=' + encodeURIComponent(val) + '; path=/; max-age=' + (days * 86400) + '; SameSite=Lax';
    }

    function detectLocale() {
        try {
            const saved = localStorage.getItem('tado_locale');
            if (saved && SUPPORTED.includes(saved)) return saved;
        } catch(e) {}

        const cookieVal = getCookie('tado_locale');
        if (cookieVal && SUPPORTED.includes(cookieVal)) return cookieVal;

        const navLang = (navigator.language || navigator.userLanguage || '').split('-')[0].toLowerCase();
        if (SUPPORTED.includes(navLang)) return navLang;

        return DEFAULT_LOCALE;
    }

    let currentLocale = detectLocale();

    function getNested(obj, path) {
        if (!obj) return undefined;
        const parts = path.split('.');
        let curr = obj;
        for (const p of parts) {
            if (curr && typeof curr === 'object' && p in curr) {
                curr = curr[p];
            } else {
                return undefined;
            }
        }
        return curr;
    }

    function t(key, fallback = '') {
        const dict = LOCALES[currentLocale] || LOCALES[DEFAULT_LOCALE];
        let val = getNested(dict, key);
        if (val !== undefined && val !== null) return val;

        const defDict = LOCALES[DEFAULT_LOCALE];
        val = getNested(defDict, key);
        if (val !== undefined && val !== null) return val;

        return fallback || key;
    }

    function applyTranslations(root = document) {
        // Translate text elements
        root.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const fallback = el.getAttribute('data-i18n-default') || el.textContent;
            if (!el.hasAttribute('data-i18n-default')) {
                el.setAttribute('data-i18n-default', fallback);
            }
            const translated = t(key, fallback);
            if (translated) el.textContent = translated;
        });

        // Translate HTML elements
        root.querySelectorAll('[data-i18n-html]').forEach(el => {
            const key = el.getAttribute('data-i18n-html');
            const fallback = el.getAttribute('data-i18n-default') || el.innerHTML;
            if (!el.hasAttribute('data-i18n-default')) {
                el.setAttribute('data-i18n-default', fallback);
            }
            const translated = t(key, fallback);
            if (translated) el.innerHTML = translated;
        });

        // Translate placeholders
        root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const fallback = el.getAttribute('data-i18n-placeholder-default') || el.placeholder;
            if (!el.hasAttribute('data-i18n-placeholder-default')) {
                el.setAttribute('data-i18n-placeholder-default', fallback);
            }
            const translated = t(key, fallback);
            if (translated) el.placeholder = translated;
        });

        // Translate titles
        root.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            const fallback = el.getAttribute('data-i18n-title-default') || el.title;
            if (!el.hasAttribute('data-i18n-title-default')) {
                el.setAttribute('data-i18n-title-default', fallback);
            }
            const translated = t(key, fallback);
            if (translated) el.title = translated;
        });

        // Translate input values (buttons)
        root.querySelectorAll('[data-i18n-value]').forEach(el => {
            const key = el.getAttribute('data-i18n-value');
            const fallback = el.getAttribute('data-i18n-value-default') || el.value;
            if (!el.hasAttribute('data-i18n-value-default')) {
                el.setAttribute('data-i18n-value-default', fallback);
            }
            const translated = t(key, fallback);
            if (translated) el.value = translated;
        });

        // Sync select picker value if exists
        const select = document.getElementById('portal-lang-select');
        if (select && select.value !== currentLocale) {
            select.value = currentLocale;
        }

        document.documentElement.lang = currentLocale;
    }

    function setLocale(lang) {
        if (!SUPPORTED.includes(lang)) return;
        currentLocale = lang;
        try { localStorage.setItem('tado_locale', lang); } catch(e) {}
        setCookie('tado_locale', lang);
        applyTranslations(document);
        window.dispatchEvent(new CustomEvent('portal:locale-changed', { detail: { locale: lang } }));
    }

    // Expose globals
    window.t = t;
    window.setLocale = setLocale;
    window.getLocale = () => currentLocale;
    window.applyTranslations = applyTranslations;
    window.PORTAL_LOCALES = LOCALES;

    // Run automatically on load
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', () => applyTranslations(document));
    } else {
        applyTranslations(document);
    }
})();
`;
}

