/**
 * Returns HTML for the language selector dropdown.
 * @param {string} activeLocale 
 * @param {string} [id='portal-lang-select']
 * @param {string} [extraClass='']
 * @returns {string}
 */
function renderLanguageSelector(activeLocale = 'en', id = 'portal-lang-select', extraClass = '') {
    const locale = SUPPORTED_LOCALES.includes(activeLocale) ? activeLocale : DEFAULT_LOCALE;
    const options = SUPPORTED_LOCALES.map(code => {
        const label = LOCALE_NAMES[code] || code.toUpperCase();
        const selected = code === locale ? 'selected' : '';
        return `<option value="${code}" ${selected}>${label}</option>`;
    }).join('');

    return `<select id="${id}" class="form-select form-select-sm bg-dark text-white border-secondary ${extraClass}" style="width: auto; cursor: pointer;" onchange="window.setLocale(this.value)">${options}</select>`;
}

